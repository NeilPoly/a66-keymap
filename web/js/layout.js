/**
 * @typedef {{id:number, legend:string, matrix:number, x:number, y:number, w:number,
 *            factoryBase:number, factoryFn:number, isKnob:boolean}} KeySpec
 */

/** @type {KeySpec[]} */
export const KEYS = RAW.map(([id, legend, matrix, x, y, w, factoryBase, factoryFn]) =>
  Object.freeze({ id, legend, matrix, x, y, w, factoryBase, factoryFn, isKnob: id === 67 }));

/** 键盘总宽（单位）与行数 */
export const WIDTH = 16;
export const ROWS = 5;

/** @returns {KeySpec | undefined} */
export function keySpec(id) {
  return Number.isInteger(id) && id >= 1 && id <= KEYS.length ? KEYS[id - 1] : undefined;
}

/** 出厂设备码：第 0 层 = 普通层，第 1 层 = Fn 层，其余为空 */
export function factoryCode(spec, layer) {
  return layer === 0 ? spec.factoryBase : layer === 1 ? spec.factoryFn : 0;
}
