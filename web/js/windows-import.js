import { L } from './l10n.js';
import { KEYS } from './layout.js';
import { Keymap, LAYER_COUNT } from './keymap.js';

// 导入原厂 Windows 驱动保存的键位配置 profile.dct
// （位置：%LOCALAPPDATA%\BYCOMBO4\A66 Keyboard\profile.dct）。
// 键记录 → 设备码的换算逐条对照原驱动的 keyinfo_to_hardware_code 行为实现。
// 与 Sources/A66Core/WindowsImport.swift 一一对应。所有 32 位运算都用 >>> 0 收成无符号数。

const byteSwap = (x) => (((x & 0xff) << 24) | ((x & 0xff00) << 8) | ((x >>> 8) & 0xff00) | (x >>> 24)) >>> 0;

/**
 * profile.dct 里的一条键记录（16 字节）：
 *   u32 (Major<<24 | Minor), u8 修饰位图, u8 VK1, u8 VK2, u8 原始VK, u32 参数, u8 灯号, u8 矩阵号, u16 保留
 */
function keyRecord(d, o) {
  const u32 = (p) => (d[o + p] | (d[o + p + 1] << 8) | (d[o + p + 2] << 16) | (d[o + p + 3] << 24)) >>> 0;
  const word0 = u32(0);
  return {
    word0, mods: d[o + 4], vk1: d[o + 5], vk2: d[o + 6], param: u32(8),
    major: word0 >>> 24, minor: word0 & 0xffffff,
  };
}

/**
 * profile.dct：偏移 0x3C 起 4 层 × 144 条 × 16 字节，第 i 条对应 K(i+1)。只取前 3 层的 K1…K67。
 * @param {Uint8Array} d
 */
export function keymapFromWindowsProfile(d) {
  const base = 0x3c, layerCount = 4, perLayer = 0x90, size = 16;
  const need = base + layerCount * perLayer * size;
  if (d.length < need) {
    throw new Error(L(`profile.dct 太短：${d.length} 字节，至少要 ${need}`, `profile.dct is too short: ${d.length} bytes, need at least ${need}`));
  }
  const k = new Keymap();
  for (let l = 0; l < LAYER_COUNT; l++) {
    for (let i = 0; i < perLayer; i++) {
      const r = keyRecord(d, base + (l * perLayer + i) * size);
      // 原驱动只看第一个 u32 是否为 0 来决定跳过
      if (r.word0 === 0) continue;
      const where = L(`第 ${l} 层 K${i + 1}：`, `Layer ${l} K${i + 1}: `);
      if (i >= KEYS.length) throw new Error(where + L('A66 没有这个键', 'A66 has no such key'));
      let code;
      try { code = windowsHardwareCode(r); } catch (e) { throw new Error(where + e.message); }
      // 原驱动的结果按小端写进键位表，换成字节顺序
      const c = byteSwap(code);
      if (c !== 0) k.layers[l].set(i + 1, c);
    }
  }
  return k;
}

// MARK: - 键记录 → 设备码（原驱动的 32 位整数形式，写进键位表时按小端存放）

export function windowsHardwareCode(r) {
  const { major, minor } = r;
  switch (major) {
    case 1: {
      const t = {
        0x11: 0x10101, 0x12: 0x10301, 0x13: 0x10201, 0x14: 0x10401, 0x15: 0x10501,
        0x16: 0x20101, 0x17: 0x30101, 0x19: 0x801, 0x1a: 0x901,
        0x1b: 0x32ff0701, 0x1c: 0x32ff0601,
      };
      if (minor in t) return t[minor] >>> 0;
      break;
    }
    case 3:
    case 4:
      if (consumerByMinor.has(minor)) return consumerByMinor.get(minor);
      break;
    case 2: {
      const { mods, vk1 } = r;
      if (mods === 0) {
        if (vk1 === 0xfa) return 0x0d; // Fn
        if (vk1 === 0xfb) return 0x10d; // Fn2
      }
      if (vk1 >= 1 && vk1 <= 5) return r.param; // 鼠标键 VK：原样用参数
      if (consumerByVK.has(vk1)) return consumerByVK.get(vk1);
      const h2 = hidUsage(r.vk2), h1 = hidUsage(vk1);
      return ((h1 << 24) | (h2 << 16) | (mods << 8)) >>> 0;
    }
    case 5:
      throw new Error(L('宏暂不支持', 'macros are not supported'));
    case 6: {
      const t = {
        0x43: 0x1d0100, 0x48: 0x160100, 0x51: 0x3d0400, 0x52: 0xf0800, 0x54: 0x150800,
        0x55: 0x70800, 0x56: 0x2e0100, 0x57: 0x2d0100, 0x5a: 0x4c0500,
        0x60: 0x7, 0x61: 0x1000007, 0x62: 0x2000007, 0x63: 0x4000007,
        0x64: 0x2000010, 0x65: 0x4000010,
        0x66: 0x7000005, 0x67: 0x7000006, 0x68: 0x7000007, 0x69: 0x7000008, 0x6a: 0x7000009,
        0xa2: 0,
      };
      if (minor in t) return t[minor] >>> 0;
      break;
    }
    case 8:
      switch (minor) {
        case 0xa2: case 0xa7: return 0;
        case 0xa4: {
          // 取参数的第 3 个字节选灯效档位
          const sel = (r.param >>> 16) & 0xff;
          let lo = 0, b1 = 0;
          if (sel >= 0xf0 && sel <= 0xf4) { lo = 1; b1 = sel - 0xf0 + 1; }
          return ((((((((r.param >>> 8) & 0xff) << 8) | (r.param & 0xff)) << 8) | b1) << 8) | lo) >>> 0;
        }
        case 0xa6: return (Math.imul((r.param - 1) >>> 0, 0x1000000) | 0x505) >>> 0;
        case 0xa8: return 0x105;
        case 0xa9: return 0x205;
        case 0xaa: return 0x405;
        case 0xab: return 6;
        case 0xad: return r.param;
        case 0xae: return 8;
        default: break;
      }
      break;
    case 9:
      // 按字节顺序书写的设备码：minor≠0 时整字反转字节序，minor=0 原样
      return minor !== 0 ? byteSwap(r.param) : r.param;
    default:
      break;
  }
  throw new Error(L(`无法换算：Major=${major} Minor=0x${minor.toString(16).toUpperCase()}`,
    `cannot convert: Major=${major} Minor=0x${minor.toString(16).toUpperCase()}`));
}

